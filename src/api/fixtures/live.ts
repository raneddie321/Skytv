const ep = (prefix = 'Episode') => (n: number) => `${prefix} ${n}`;
const series = (slug: string, title: string, synopsis: string, durations: number[], certification = '15'): ProgrammeTemplate => ({
  title,
  synopsis,
  durations,
  art: { slug },
  subtitle: (n) => `Season 1, Episode ${(n % 6) + 1}`,
  certification,
});
const film = (slug: string, title: string, synopsis: string, minutes: number, certification = '12'): ProgrammeTemplate => ({
  title,
  synopsis,
  durations: [minutes],
  art: { slug },
  certification,
});
const generic = (programme: string, title: string, synopsis: string, durations: number[], extra: Partial<ProgrammeTemplate> = {}): ProgrammeTemplate => ({
  title,
  synopsis,
  durations,
  art: { programme },
  ...extra,
});

