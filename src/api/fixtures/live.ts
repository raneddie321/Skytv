const DAY_MS = 24 * 60 * 60 * 1000;

function utcDayStart(t: number): number {
  return Math.floor(t / DAY_MS) * DAY_MS;
}

function programmeImage(tpl: ProgrammeTemplate): string {
  return 'slug' in tpl.art ? demoArt.backdrop(tpl.art.slug) : programmeArtUrl(tpl.art.programme);
}

function catalogIdFor(tpl: ProgrammeTemplate): string | undefined {
  if (!('slug' in tpl.art)) return undefined;
  const isMovie = tpl.durations.length === 1 && tpl.durations[0] >= 80;
  return `demo:${isMovie ? 'movie' : 'tv'}:${tpl.art.slug}`;
}

/** Generates one UTC day of programmes for a channel. Deterministic for (channel, day). */
export function generateDay(channel: DemoChannelDef, dayStart: number): Programme[] {
  const rand = mulberry32(hashString(`${channel.id}:${dayStart}`));
  const out: Programme[] = [];
  let t = dayStart;
  let n = 0;
  let idx = Math.floor(rand() * channel.programmes.length);
  while (t < dayStart + DAY_MS) {
    const tpl = channel.programmes[idx % channel.programmes.length];
    idx += 1 + (rand() < 0.25 ? 1 : 0);
    const minutes = tpl.durations[Math.floor(rand() * tpl.durations.length)];
    const end = Math.min(t + minutes * 60_000, dayStart + DAY_MS);
    out.push({
      id: `${channel.id}:${t}`,
      channelId: channel.id,
      title: tpl.title,
      subtitle: tpl.subtitle?.(n + 1),
      synopsis: tpl.synopsis,
      start: new Date(t).toISOString(),
      end: new Date(end).toISOString(),
      imageUrl: programmeImage(tpl),
      certification: tpl.certification,
      catalogId: catalogIdFor(tpl),
      isLive: tpl.live,
      isDemo: true,
    });
    t = end;
    n++;
  }
  return out;
}

export function scheduleFor(channel: DemoChannelDef, from: Date, to: Date): Programme[] {
  const out: Programme[] = [];
  for (let day = utcDayStart(from.getTime()); day < to.getTime(); day += DAY_MS) {
    for (const p of generateDay(channel, day)) {
      if (Date.parse(p.end) > from.getTime() && Date.parse(p.start) < to.getTime()) out.push(p);
    }
  }
  return out;
}

export function toChannel(def: DemoChannelDef): Channel {
  const { logo: _logo, programmes: _programmes, ...rest } = def;
  return { ...rest, isDemo: true };
}

export class FixtureLiveTv implements LiveTvService, EpgService {
  constructor(private readonly latencyMs = 0) {}

  private async delay<T>(value: T): Promise<T> {
    if (this.latencyMs > 0) await new Promise((r) => setTimeout(r, this.latencyMs));
    return value;
  }

  async getChannels(): Promise<Channel[]> {
    return this.delay([...DEMO_CHANNELS].sort((a, b) => a.number - b.number).map(toChannel));
  }

  async getSchedule(channelIds: string[], from: Date, to: Date): Promise<Record<string, Programme[]>> {
    const out: Record<string, Programme[]> = {};
    for (const id of channelIds) {
      const def = DEMO_CHANNELS.find((c) => c.id === id);
      if (def) out[id] = scheduleFor(def, from, to);
    }
    return this.delay(out);
  }
}

